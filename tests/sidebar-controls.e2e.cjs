const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
;(async () => {
  const browser = await chromium.launch({ executablePath: process.env.NORMAL_TEST_BROWSER || undefined, headless: true })
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } })
    const errors = []; page.on('pageerror', e => errors.push(e.message))
    const base = process.env.NORMAL_TEST_URL || 'http://127.0.0.1:5178/'
    const shots = process.env.SIDEBAR_SHOTS
    if (shots) fs.mkdirSync(shots, { recursive: true })
    async function screenshot(name) { if (shots) await page.screenshot({ path: path.join(shots, name + '.png') }) }
    await page.goto(base + '#/sprite-slicer')
    const sidebar = page.locator('.sidebar-content')
    await sidebar.waitFor()
    assert.equal(await sidebar.getByRole('textbox', { name: '命名前缀', exact: true }).isDisabled(), true)
    assert.equal(await sidebar.getByRole('button', { name: '新建文件夹', exact: true }).isDisabled(), true)
    await screenshot('empty')
    const png = await page.evaluate(() => {
      const inst = document.querySelector('.sidebar-content').__vueParentComponent.props.store
      window.sidebarStore = inst
      inst.setPendingRestore([{ name: 'part-a', rect: [0, 0, 64, 64] }, { name: 'part-b', rect: [64, 0, 64, 64] }])
      const canvas = document.createElement('canvas'); canvas.width = 128; canvas.height = 64
      const ctx = canvas.getContext('2d'); ctx.fillStyle = '#67a56d'; ctx.fillRect(8, 8, 46, 48); ctx.fillStyle = '#c17953'; ctx.fillRect(74, 12, 40, 40)
      return canvas.toDataURL().split(',')[1]
    })
    const picker = sidebar.locator('.dropzone')
    await picker.focus()
    const chooserPromise = page.waitForEvent('filechooser')
    await picker.press('Enter')
    const chooser = await chooserPromise
    await chooser.setFiles({ name: 'sidebar.png', mimeType: 'image/png', buffer: Buffer.from(png, 'base64') })
    await page.waitForFunction(() => window.sidebarStore.state.sprites.length === 2)
    await screenshot('auto')
    const sliderWidth = await sidebar.getByRole('slider', { name: '容差', exact: true }).evaluate(e => e.getBoundingClientRect().width)
    assert.ok(sliderWidth > 100, 'slider should fill the available sidebar width')
    await sidebar.getByRole('slider', { name: '容差', exact: true }).fill('80')
    await sidebar.getByRole('button', { name: '重置容差', exact: true }).click()
    assert.equal(await sidebar.getByRole('slider', { name: '容差', exact: true }).inputValue(), '50')
    assert.equal(await sidebar.getByRole('slider', { name: '溢色修正', exact: true }).inputValue(), '70')
    assert.equal(await sidebar.getByRole('button', { name: '重置容差', exact: true }).count(), 0)
    assert.equal(await sidebar.getByRole('button', { name: '新建文件夹', exact: true }).isDisabled(), true)
    const tags = sidebar.getByRole('textbox', { name: '标签', exact: true })
    await tags.fill('first'); await tags.press('Enter'); await tags.fill('second'); await tags.press('Tab')
    assert.equal(await sidebar.locator('.tag-chip').count(), 2)
    await sidebar.getByRole('textbox', { name: '命名前缀', exact: true }).fill('renamed')
    await page.waitForFunction(() => window.sidebarStore.state.sprites.every(s => s.name.startsWith('renamed-')))
    await page.evaluate(async () => { const { useSettings } = await import('/src/shared/settings/index.ts'); useSettings().settings.spriteSlicer.defaults.namePrefix = 'configured' })
    await sidebar.getByRole('button', { name: '重置命名前缀', exact: true }).click()
    assert.equal(await sidebar.getByRole('textbox', { name: '命名前缀', exact: true }).inputValue(), 'configured')
    const composite = sidebar.getByRole('checkbox', { name: '合成图 (PNG)', exact: true })
    await composite.check()
    const metadata = sidebar.getByRole('switch', { name: '附带坐标 JSON', exact: true })
    const before = await metadata.isChecked(); await metadata.focus(); await metadata.press('Space'); assert.equal(await metadata.isChecked(), !before)
    await composite.uncheck(); assert.equal(await metadata.isDisabled(), true)
    await composite.check()
    const normals = sidebar.getByRole('switch', { name: '同时导出法线', exact: true })
    await normals.focus(); await normals.press('Space'); assert.equal(await normals.isChecked(), true)
    await sidebar.getByRole('button', { name: '重置同时导出法线', exact: true }).click()
    assert.equal(await normals.isChecked(), false, 'reset must not also toggle the surrounding switch label')
    const mode = sidebar.getByRole('group', { name: '切图模式', exact: true })
    await mode.getByRole('button', { name: '智能检测', exact: true }).focus()
    await page.keyboard.press('ArrowRight')
    await sidebar.getByRole('spinbutton', { name: '列数', exact: true }).waitFor()
    assert.equal(await mode.getByRole('button', { name: '手动网格', exact: true }).evaluate(e => e === document.activeElement), true)
    const cols = sidebar.getByRole('spinbutton', { name: '列数', exact: true })
    const rows = sidebar.getByRole('spinbutton', { name: '行数', exact: true })
    await cols.fill('2'); await cols.press('Tab'); await rows.fill('1'); await rows.press('Tab')
    await page.waitForFunction(() => window.sidebarStore.state.sprites.length === 2)
    await cols.fill('0'); await cols.press('Tab'); assert.equal(await cols.inputValue(), '1')
    await cols.fill(''); await cols.press('Tab'); assert.equal(await cols.inputValue(), '1')
    await cols.fill('2'); await cols.press('Tab')
    await sidebar.getByRole('button', { name: '重置列数', exact: true }).click()
    assert.equal(await cols.inputValue(), '6')
    assert.equal(await rows.inputValue(), '1')
    await cols.fill('2'); await cols.press('Tab')
    await screenshot('grid')
    await sidebar.getByRole('group', { name: '去背', exact: true }).getByRole('button', { name: '不去背', exact: true }).click()
    assert.equal(await sidebar.getByRole('slider', { name: '容差', exact: true }).count(), 0)
    const arrange = sidebar.getByRole('group', { name: '排列模式', exact: true })
    for (const label of ['标准化', '自动排列', '无']) {
      await arrange.getByRole('button', { name: label, exact: true }).click()
      await page.waitForFunction(() => window.sidebarStore.state.sprites.length === 2)
    }
    await arrange.getByRole('button', { name: '标准化', exact: true }).click()
    await arrange.getByRole('button', { name: '重置排列模式', exact: true }).click()
    assert.equal(await page.evaluate(() => window.sidebarStore.state.arrangeMode), 'none')
    await screenshot('no-background')
    const overflow = await sidebar.evaluate(el => el.scrollWidth > el.clientWidth + 1)
    assert.equal(overflow, false)
    await page.setViewportSize({ width: 1000, height: 720 })
    await sidebar.getByRole('button', { name: '导出到本地', exact: true }).scrollIntoViewIfNeeded()
    assert.equal(await sidebar.evaluate(el => el.scrollWidth > el.clientWidth + 1), false)
    await screenshot('compact-output')
    await page.setViewportSize({ width: 1440, height: 1100 })
    await page.goto(base + '#/tileset-maker')
    await page.getByRole('button', { name: 'SDF 纹理模式', exact: true }).waitFor()
    await screenshot('tileset-sdf')
    await page.getByRole('textbox', { name: '地形名称', exact: true }).fill('terrain-check')
    await page.getByRole('button', { name: '子瓦片模式', exact: true }).click()
    await page.getByRole('checkbox', { name: '品红转透明', exact: true }).check()
    await page.locator('.ninegrid-source-panel').getByRole('slider', { name: '容差', exact: true }).fill('60')
    await page.locator('.ninegrid-source-panel').getByRole('button', { name: '重置容差', exact: true }).click()
    assert.equal(await page.locator('.ninegrid-source-panel').getByRole('slider', { name: '容差', exact: true }).inputValue(), '30')
    await screenshot('tileset-subtile')
    assert.equal(await page.locator('.ninegrid-source-panel .slider-input').count(), 1)
    await page.goto(base + '#/scene-region-editor')
    await page.locator('.no-selection').waitFor()
    await page.evaluate(b => {
      const store = document.querySelector('.no-selection').__vueParentComponent.props.store
      window.sceneSidebarStore = store
      store.loadImage('data:image/png;base64,' + b, 128, 64)
      store.addRegion([{x:5,y:5},{x:50,y:5},{x:50,y:50},{x:5,y:50}])
    }, png)
    const properties = page.locator('.region-property-content')
    await properties.getByRole('textbox', { name: '名称', exact: true }).fill('sidebar-region')
    await properties.getByRole('textbox', { name: '名称', exact: true }).press('Tab')
    await properties.getByRole('slider', { name: '不透明度', exact: true }).fill('65')
    assert.equal(await page.evaluate(() => window.sceneSidebarStore.state.regions[0].name), 'sidebar-region')
    assert.ok(await page.evaluate(() => window.sceneSidebarStore.state.regions[0].groups.includes('occlude_opacity_65')))
    assert.equal(await page.getByRole('button', { name: '导出 tscn', exact: true }).isEnabled(), true)
    await screenshot('scene-occlude')
    await properties.getByRole('button', { name: '碰撞区域', exact: true }).click()
    assert.equal(await properties.getByRole('slider', { name: '不透明度', exact: true }).count(), 0)
    await screenshot('scene-collision')
    await properties.getByRole('button', { name: '遮挡区域', exact: true }).click()
    await properties.getByRole('button', { name: '遮挡行为', exact: true }).focus()
    await page.keyboard.press('Space')
    assert.equal(await properties.getByRole('slider', { name: '不透明度', exact: true }).isVisible(), false)
    await page.keyboard.press('Enter')
    assert.equal(await properties.getByRole('slider', { name: '不透明度', exact: true }).isVisible(), true)
    assert.deepEqual(errors, [])
    console.log('Sidebar: keyboard upload, mode branches, numeric validation, tags, toggles, layouts, tileset modes and scene properties passed')
  } finally { await browser.close() }
})().catch(e => { console.error(e); process.exit(1) })
