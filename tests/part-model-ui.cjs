// Run against dev:web with PLAYWRIGHT_MODULE pointing to an installed Playwright.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs')

async function main() {
  const browser = await chromium.launch({ channel: 'msedge', headless: true })
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } }), errors = []
    page.on('pageerror', error => errors.push(String(error)))
    await page.goto(process.env.G_STUDIO_TEST_URL || 'http://localhost:5173')
    await page.locator('.module-card').first().waitFor()
    await page.evaluate(async () => {
      const { loadPartLibrary } = await import('/src/shared/parts/library.ts')
      const { openPartEditor } = await import('/src/shared/parts/editor-session.ts')
      await loadPartLibrary()
      openPartEditor({ assetId: 'example:chair', origin: 'scene' })
    })
    const editor = page.locator('.part-editor'), select = editor.locator('.model-trigger')
    const menu = editor.getByRole('menu'), options = menu.getByRole('menuitemradio')
    async function choose(label) {
      if (await select.getAttribute('aria-expanded') !== 'true') await select.click()
      await menu.getByRole('menuitemradio', { name: label, exact: true }).click()
      assert.equal(await menu.isVisible(), true, 'choosing a card keeps comparison available')
      await page.keyboard.press('Escape')
    }
    await select.waitFor()
    await editor.getByRole('button', { name: '模型', exact: true }).click()
    await editor.locator('.viewport-stage[aria-busy="false"] canvas').waitFor()
    await select.click()
    assert.deepEqual(await options.allTextContents(), ['靠背椅 · 模板', '轮廓近似'])
    await page.waitForFunction(() => document.querySelectorAll('.model-thumbnail canvas[data-preview-state="ready"]').length === 2)
    const cardFrames = await menu.locator('canvas').evaluateAll(nodes => nodes.map(canvas => canvas.toDataURL()))
    await page.waitForTimeout(500)
    const rotatedFrames = await menu.locator('canvas').evaluateAll(nodes => nodes.map(canvas => canvas.toDataURL()))
    assert.ok(cardFrames.every((image, i) => image !== rotatedFrames[i]), 'template and silhouette both rotate')
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await page.waitForTimeout(100)
    const stillFrames = await menu.locator('canvas').evaluateAll(nodes => nodes.map(canvas => canvas.toDataURL()))
    await page.waitForTimeout(200)
    assert.deepEqual(await menu.locator('canvas').evaluateAll(nodes => nodes.map(canvas => canvas.toDataURL())), stillFrames)
    await page.emulateMedia({ reducedMotion: 'no-preference' })
    const viewCanvas = editor.locator('.part-preview canvas').first()
    const originalFrame = await viewCanvas.evaluate(canvas => canvas.toDataURL())
    const originalAsset = await page.evaluate(async()=>{const {partLibrary}=await import('/src/shared/parts/library.ts');return JSON.stringify(partLibrary['example:chair'])})
    const originalWidth = await editor.getByRole('slider',{name:'模型宽度',exact:true}).inputValue()
    await menu.getByRole('menuitemradio',{name:'轮廓近似',exact:true}).hover()
    await page.waitForFunction(frame=>document.querySelector('.part-preview canvas')?.toDataURL()!==frame,originalFrame)
    assert.equal(await menu.getByRole('menuitemradio',{name:'靠背椅 · 模板',exact:true}).getAttribute('aria-checked'),'true','hover never changes the checked option')
    assert.equal(await select.textContent(),'靠背椅 · 模板')
    assert.equal(await editor.getByRole('slider',{name:'模型宽度',exact:true}).inputValue(),originalWidth)
    assert.ok(!(await editor.locator('header span').last().innerText()).includes('●'),'hover must not dirty the part')
    await page.mouse.move(1300,700)
    await page.waitForFunction(frame=>document.querySelector('.part-preview canvas')?.toDataURL()===frame,originalFrame)
    await menu.getByRole('menuitemradio',{name:'轮廓近似',exact:true}).hover()
    await page.keyboard.press('Control+s')
    await page.waitForFunction(()=>!document.querySelector('.part-editor footer .primary')?.disabled)
    assert.equal(await page.evaluate(async()=>{const {partLibrary}=await import('/src/shared/parts/library.ts');return JSON.stringify(partLibrary['example:chair'])}),originalAsset,'saving during hover cannot alter the asset')
    if (await select.getAttribute('aria-expanded') !== 'true') await select.click()
    assert.equal(await menu.locator('button').first().textContent(), '生成模型')
    await page.keyboard.press('Home')
    assert.equal(await menu.getByRole('menuitem', { name: '生成模型', exact: true }).evaluate(el => el === document.activeElement), true)
    await page.keyboard.press('Enter')
    await page.locator('.generation-overlay').waitFor()
    assert.equal(await select.textContent(), '靠背椅 · 模板', 'generating does not change the selection')
    assert.equal(await menu.count(), 0)
    await page.keyboard.press('Escape')
    await page.locator('.generation-overlay').waitFor({ state: 'detached' })
    await select.focus()
    await page.keyboard.press('ArrowDown')
    await page.keyboard.press('End')
    await page.keyboard.press('Enter')
    assert.equal(await select.textContent(), '轮廓近似')
    assert.equal(await menu.isVisible(), true)
    await page.keyboard.press('Escape')
    assert.equal(await menu.count(), 0)
    assert.equal(await editor.count(), 1, 'Escape closes the menu, not the editor')
    assert.equal(await select.evaluate(el => el === document.activeElement), true)
    await select.click()
    await editor.locator('header strong').click()
    assert.equal(await menu.count(), 0, 'outside click dismisses the menu')
    await select.click()
    await select.click()
    assert.equal(await menu.count(), 0, 'clicking the trigger again closes the menu')
    await select.click()
    await page.keyboard.press('Tab')
    assert.equal(await menu.count(), 0, 'Tab dismisses the menu')
    assert.equal(await editor.getByRole('slider', { name: '模型宽度', exact: true }).evaluate(el => el === document.activeElement), true)
    const resetCount = () => editor.locator('.parameter-reset:not(.unchanged)').count()
    assert.equal(await resetCount(), 0)
    await choose('轮廓近似')
    assert.equal(await resetCount(), 0)
    await choose('靠背椅 · 模板')
    assert.equal(await resetCount(), 0)
    await select.click()
    await page.waitForFunction(() => document.querySelectorAll('.model-thumbnail canvas[data-preview-state="ready"]').length === 2)
    fs.mkdirSync('.generation-test/part-model', { recursive: true })
    await page.screenshot({ path: '.generation-test/part-model/model-menu.png' })
    await page.keyboard.press('Escape')
    await editor.locator('footer .primary').click()
    await editor.waitFor({ state: 'detached' })
    // Seed a completed standalone task for exactly the same image as a new part.
    await page.evaluate(async () => {
      const { createPart } = await import('/src/shared/parts/schema.ts')
      const { savePart } = await import('/src/shared/parts/library.ts')
      const { openPartEditor } = await import('/src/shared/parts/editor-session.ts')
      const { generationJobs, loadGenerationJobs, persistJob } = await import('/src/shared/generation/jobs.ts')
      const { sha256 } = await import('/src/shared/generation/client.ts')
      const { meshDataUri } = await import('/src/shared/parts/mesh.ts')
      await loadGenerationJobs()
      const canvas = document.createElement('canvas'); canvas.width = 64; canvas.height = 96
      const ctx = canvas.getContext('2d'); ctx.fillStyle = '#b38a58'; ctx.fillRect(12, 8, 40, 80)
      const image = canvas.toDataURL('image/png'), hash = await sha256(await (await fetch(image)).arrayBuffer())
      const binary = new Float32Array([0, 0, 0, 1, 0, 0, 0, 2, 1])
      const gltf = { asset: { version: '2.0' }, buffers: [{ byteLength: 36 }], bufferViews: [{ buffer: 0, byteLength: 36 }], accessors: [{ bufferView: 0, componentType: 5126, count: 3, type: 'VEC3' }], meshes: [{ primitives: [{ attributes: { POSITION: 0 } }] }], nodes: [{ mesh: 0 }], scenes: [{ nodes: [0] }], scene: 0 }
      const json = JSON.stringify(gltf), encoded = new TextEncoder().encode(json + ' '.repeat((4 - json.length % 4) % 4))
      const bytes = new ArrayBuffer(28 + encoded.length + 36), view = new DataView(bytes)
      for (const [offset, value] of [[0, 0x46546c67], [4, 2], [8, bytes.byteLength], [12, encoded.length], [16, 0x4e4f534a], [20 + encoded.length, 36], [24 + encoded.length, 0x004e4942]]) view.setUint32(offset, value, true)
      new Uint8Array(bytes, 20, encoded.length).set(encoded); new Uint8Array(bytes, 28 + encoded.length).set(new Uint8Array(binary.buffer))
      const part = createPart('模型切换测试', { uri: image, width: 64, height: 96 }, 'model-ui-part')
      await savePart(part)
      const job = { localId: 'model-ui-model', createdAt: 1, name: part.name, image, connection: {}, request: { inputSha256: hash }, model: { kind: 'mesh', size: [1, 2, 1], mesh: { uri: meshDataUri(bytes), sha256: await sha256(bytes), inputSha256: hash, providerId: 'fixture', warnings: [] } } }
      await persistJob(job); generationJobs.push(job)
      const secondBytes = bytes.slice(0)
      new Float32Array(secondBytes, 28 + encoded.length)[6] = .8
      const second = { ...job, localId: 'model-ui-model-2', createdAt: 2, model: { ...job.model, mesh: { ...job.model.mesh, uri: meshDataUri(secondBytes), sha256: await sha256(secondBytes) } } }
      await persistJob(second); generationJobs.push(second)
      openPartEditor({ assetId: part.id, origin: 'slicer' })
    })
    await page.waitForFunction(() => document.querySelector('.model-trigger')?.textContent === '已生成模型 1')
    await select.click()
    assert.deepEqual(await options.allTextContents(), ['已生成模型 1', '已生成模型 2', '轮廓近似'])
    await page.waitForFunction(() => document.querySelectorAll('.model-thumbnail canvas[data-preview-state="ready"]').length === 3)
    const generatedFrames = await options.locator('canvas').evaluateAll(nodes => nodes.map(canvas => canvas.toDataURL()))
    assert.notEqual(generatedFrames[0], generatedFrames[1], 'each model card renders its own model')
    await page.waitForTimeout(500)
    const generatedRotated = await options.locator('canvas').evaluateAll(nodes => nodes.map(canvas => canvas.toDataURL()))
    assert.ok(generatedFrames.every((image, i) => image !== generatedRotated[i]), 'all model cards rotate')
    await page.screenshot({ path: '.generation-test/part-model/model-cards.png' })
    await page.keyboard.press('Escape')
    assert.equal(await resetCount(), 0)
    await choose('轮廓近似'); assert.equal(await resetCount(), 0)
    await choose('已生成模型 2'); assert.equal(await resetCount(), 0)
    await choose('已生成模型 1'); assert.equal(await resetCount(), 0)
    const width = editor.getByRole('slider', { name: '模型宽度', exact: true })
    await width.fill('1.5'); assert.equal(await resetCount(), 1)
    await editor.getByRole('button', { name: '重置模型宽度', exact: true }).click()
    assert.equal(await width.inputValue(), '1'); assert.equal(await resetCount(), 0)
    await choose('轮廓近似')
    await select.click()
    await menu.getByRole('menuitemradio',{name:'已生成模型 1',exact:true}).hover()
    assert.equal(await menu.getByRole('menuitemradio',{name:'轮廓近似',exact:true}).getAttribute('aria-checked'),'true')
    // Dispatch without moving the mouse: saving must be safe even while hover is active.
    await editor.locator('footer .primary').dispatchEvent('click'); await editor.waitFor({ state: 'detached' })
    assert.equal(await page.evaluate(async()=>{const {partLibrary}=await import('/src/shared/parts/library.ts');return partLibrary['model-ui-part'].model.kind}),'silhouette','Save and return persists the checked model, never the hovered model')
    await page.evaluate(async () => {
      const { generationJobs, removeJob } = await import('/src/shared/generation/jobs.ts')
      await removeJob(generationJobs.find(job => job.localId === 'model-ui-model'))
      await removeJob(generationJobs.find(job => job.localId === 'model-ui-model-2'))
    })
    await page.reload(); await page.locator('.module-card').first().waitFor()
    await page.evaluate(async () => {
      const { loadPartLibrary } = await import('/src/shared/parts/library.ts')
      const { openPartEditor } = await import('/src/shared/parts/editor-session.ts')
      await loadPartLibrary(); openPartEditor({ assetId: 'model-ui-part', origin: 'scene' })
    })
    await select.waitFor()
    assert.equal(await select.textContent(), '轮廓近似', 'saved explicit selection is respected')
    await choose('已生成模型 1')
    assert.equal(await width.inputValue(), '1'); assert.equal(await resetCount(), 0)
    await editor.locator('.viewport-stage[aria-busy="false"] .light-guide').waitFor()
    assert.equal(await editor.locator('.viewport-error').count(), 0)
    fs.mkdirSync('.generation-test/part-model', { recursive: true })
    await page.screenshot({ path: '.generation-test/part-model/model-selection.png' })
    await page.setViewportSize({ width: 390, height: 760 })
    await select.click()
    const bounds = await menu.boundingBox()
    assert.ok(bounds && bounds.x >= 0 && bounds.y >= 0 && bounds.x + bounds.width <= 390 && bounds.y + bounds.height <= 760, 'menu stays inside the narrow viewport')
    await page.screenshot({ path: '.generation-test/part-model/model-menu-narrow.png' })
    await page.keyboard.press('Escape')
    await page.evaluate(() => {
      const original = HTMLCanvasElement.prototype.getContext
      window.restoreCardContext = () => { HTMLCanvasElement.prototype.getContext = original }
      HTMLCanvasElement.prototype.getContext = function (type, ...args) {
        // Only deny the detached renderer used by card previews.
        if (!this.isConnected && type.startsWith('webgl')) return null
        return original.call(this, type, ...args)
      }
    })
    await select.click()
    await page.waitForFunction(() => document.querySelectorAll('.model-thumbnail canvas[data-preview-state="error"]').length === 3)
    assert.equal(await menu.locator('.model-placeholder:visible').count(), 3)
    const silhouette = menu.getByRole('menuitemradio', { name: '轮廓近似', exact: true })
    assert.ok((await silhouette.locator('.model-placeholder path').getAttribute('d')).startsWith('M9 3h6'))
    await silhouette.click()
    assert.equal(await select.textContent(), '轮廓近似', 'placeholder cards remain selectable')
    await page.evaluate(() => window.restoreCardContext())
    assert.deepEqual(errors, [])
    console.log('PASS: rotating model/template/silhouette cards, reduced motion, fallback icons, generation action, keyboard navigation, narrow viewport, switching and reload')
  } finally { await browser.close() }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
