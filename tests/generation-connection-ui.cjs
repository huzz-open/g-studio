// Run against npm run dev:web; PLAYWRIGHT_MODULE may point to a bundled runtime.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs')

;(async () => {
  const browser = await chromium.launch({ channel: process.env.G_STUDIO_TEST_BROWSER_CHANNEL || 'chrome', headless: true })
  try {
    const context = await browser.newContext({ viewport: { width: 1400, height: 1000 } })
    const page = await context.newPage(), errors = []
    page.on('pageerror', error => errors.push(String(error)))
    let apiRequests = 0, lookups = 0, ready = false
    const headers = { 'access-control-allow-origin': '*', 'access-control-allow-headers': 'authorization,content-type', 'access-control-allow-methods': 'GET,POST,OPTIONS' }
    const caps = { protocolVersion: 1, providers: [{ providerId: 'hunyuan-mini', name: 'Hunyuan', state: 'loading', acceptsJobs: true, tags: ['推荐','快速'], strategy: 'resident', parameters: {} }], limits: { inputBytes: 10485760, inputDimension: 2048, outputBytes: 134217728, concurrency: 1, queue: 8 }, targetFaces: { min: 1000, max: 40000, default: 12000 } }
    caps.providers.push(
      { providerId: 'hunyuan-turbo', name: 'Hunyuan3D-2-Turbo', state: 'disabled', acceptsJobs: false, tags: ['均衡'], parameters: {} },
      { providerId: 'hunyuan-2-1', name: 'Hunyuan3D-2.1 Shape', state: 'failed', acceptsJobs: false, error: 'CUDA out of memory', tags: ['精细'], parameters: {} },
    )
    await page.route('**/__generation/connection', route => { lookups++; return route.fulfill({ json: { baseUrl: 'http://127.0.0.1:8765', token: 'local-only' } }) })
    await page.route('http://192.168.1.20:8765/**', async route => {
      apiRequests++
      if (route.request().method() === 'OPTIONS') return route.fulfill({ status: 204, headers })
      if (!ready) return route.abort()
      assert.equal(route.request().headers().authorization, 'Bearer direct-test-token')
      return route.fulfill({ headers, json: route.request().url().includes('capabilities') ? caps : { deviceType: 'gpu', backend: 'mps' } })
    })
    const base = process.env.G_STUDIO_TEST_URL || 'http://localhost:5173'
    await page.goto(base + '/#/sprite-slicer')
    await page.locator('.nav-link').filter({ hasText: '模型生成' }).click()
    await page.locator('#generation-url').waitFor()
    assert.equal(await page.locator('#generation-url').inputValue(), '')
    assert.equal(await page.locator('.generation-settings .seg-control').count(), 0)
    assert.equal(await page.locator('#generation-relay, #generation-pair').count(), 0)
    assert.equal(apiRequests, 0)
    assert.equal(lookups, 0)
    assert.equal(await page.locator('.generation-install').getAttribute('open'), null)
    await page.locator('.generation-install > summary').click()
    let command = await page.locator('.install-command').innerText()
    assert.equal(command, `curl -fsSL '${base}/install-generation.sh' | bash -s -- --site '${base}/'`)
    assert.ok(!command.includes('--host'))
    await context.grantPermissions(['clipboard-read', 'clipboard-write'])
    const copyButton = page.locator('.copy-install')
    await copyButton.click()
    await page.locator('.copy-install.copied').waitFor()
    assert.equal(await page.evaluate(() => navigator.clipboard.readText()), command)
    assert.equal(await copyButton.innerText(), '已复制')
    await page.locator('.copy-install.copied').waitFor({ state: 'hidden', timeout: 3000 })
    assert.equal(await copyButton.innerText(), '')
    assert.equal(await page.locator('.generation-install > p').count(), 0)
    await page.locator('.install-scope input').check()
    command = await page.locator('.install-command').innerText()
    assert.ok(command.endsWith('--host 0.0.0.0'))
    const help = page.locator('.gs-row').filter({ has: page.locator('#generation-url') }).locator('.info-hint-button')
    await help.hover()
    await page.getByRole('tooltip').filter({ hasText: '浏览器直接调用' }).waitFor()
    await help.focus()
    await page.keyboard.press('Escape')
    await page.getByRole('tooltip').waitFor({ state: 'hidden' })
    fs.mkdirSync('.generation-test/connection-ui', { recursive: true })
    await page.screenshot({ path: '.generation-test/connection-ui/direct-setup.png' })
    await page.locator('.test-connection').click()
    await page.getByText('请先填写生成服务的 API 地址。', { exact: true }).waitFor()
    assert.equal(await page.locator('#generation-url').inputValue(), '')
    assert.equal(apiRequests, 0)
    await page.locator('#generation-url').fill('http://192.168.1.20:8765')
    await page.locator('#generation-token').fill('direct-test-token')
    await page.locator('.test-connection').click()
    await page.locator('.connection-status.failed').waitFor()
    await page.getByText(/无法连接生成服务/).waitFor()
    ready = true
    await page.evaluate(async () => { (await import('/src/shared/generation/settings.ts')).generationSettings.providerId = 'hunyuan-turbo' })
    await page.locator('.test-connection').click()
    await page.locator('.connection-status.preparing').waitFor()
    const spinner = page.locator('.connection-status.preparing')
    assert.notEqual(await spinner.evaluate(el => getComputedStyle(el).animationName), 'none')
    assert.equal(await spinner.evaluate(el => getComputedStyle(el).animationPlayState), 'running')
    await page.locator('.device-tag').filter({ hasText: 'GPU · Apple MPS' }).waitFor()
    assert.match(await page.locator('#generation-provider').innerText(), /Hunyuan.*推荐.*快速.*已启用/s)
    assert.match(await page.locator('.provider-status').innerText(), /加载中/)
    assert.match(await page.locator('.connection-summary').getAttribute('title'), /Hunyuan.*加载中/)
    await page.locator('#generation-provider').click()
    const disabledOption = page.getByRole('option', { name: /Hunyuan3D-2-Turbo/ })
    assert.equal(await disabledOption.isDisabled(), true)
    assert.match(await disabledOption.innerText(), /未启用/)
    await disabledOption.dispatchEvent('click')
    assert.match(await page.locator('#generation-provider').innerText(), /^Hunyuan\s/)
    await page.screenshot({ path: '.generation-test/connection-ui/model-options.png' })
    // Arrow navigation skips the disabled Turbo and reaches the enabled, failed model.
    await page.keyboard.press('ArrowDown')
    await page.keyboard.press('Enter')
    await page.locator('.provider-status.failed').waitFor()
    assert.match(await page.locator('#generation-provider').innerText(), /Hunyuan3D-2.1 Shape.*已启用/s)
    await page.locator('.test-connection').click()
    await page.locator('.connection-status.failed').waitFor()
    assert.match(await page.locator('#generation-provider').innerText(), /Hunyuan3D-2.1 Shape/)
    await page.locator('#generation-provider').click()
    await page.getByRole('option', { name: /Hunyuan 推荐/ }).click()
    await page.locator('.connection-status.preparing').waitFor()
    for (const provider of caps.providers) Object.assign(provider, { state: 'disabled', acceptsJobs: false, error: null, tags: provider.tags.filter(tag => tag !== '推荐') })
    await page.locator('.test-connection').click()
    await page.locator('.connection-status.disabled').waitFor()
    assert.equal(await page.locator('.connection-status.failed').count(), 0)
    assert.match(await page.locator('#generation-provider').innerText(), /请选择已启用的模型/)
    await page.locator('#generation-provider').click()
    assert.equal(await page.locator('.provider-options').getByRole('option').count(), 3)
    assert.equal(await page.locator('.provider-options [role="option"]:disabled').count(), 3)
    await page.keyboard.press('Escape')
    assert.equal(lookups, 0, 'a remote API must never use local development credentials')
    await page.locator('#generation-url').fill('http://public.example.com:8765')
    assert.equal(await page.locator('#generation-token').inputValue(), '')
    await page.locator('#generation-token').fill('public-test-token')
    await page.locator('.test-connection').click()
    await page.getByText('公网 API 需要 HTTPS。本机或内网直连可使用 HTTP。', { exact: true }).waitFor()
    // A local address is no exception: no credentials are fetched or filled.
    await page.locator('#generation-url').fill('http://127.0.0.1:8765')
    assert.equal(await page.locator('#generation-token').inputValue(), '')
    await page.locator('.test-connection').click()
    await page.getByText('请填写此 API 对应的访问凭证，可从服务启动终端获取或向服务提供者索取。', { exact: true }).waitFor()
    await page.locator('#generation-token').fill('typed-token')
    const requestsBefore = apiRequests
    await page.evaluate(async () => {
      await (await import('/src/shared/generation/connection.ts')).checkGenerationConnection({ background: true })
    })
    assert.equal(apiRequests, requestsBefore)
    assert.equal(lookups, 0, 'local APIs must not discover development credentials either')
    assert.equal(await page.locator('#generation-token').inputValue(), 'typed-token')
    assert.deepEqual(errors, [])
    // Migrating a saved relay connection leaves an unconfigured direct API.
    await page.evaluate(() => localStorage.setItem('g-studio-generation-device-v1', JSON.stringify({ mode: 'relay', relayUrl: 'https://old.example', relayToken: 'old-token', deviceId: 'old-device', baseUrl: 'http://127.0.0.1:8765', token: 'old-direct' })))
    await page.reload()
    const migrated = await page.evaluate(async () => (await import('/src/shared/generation/settings.ts')).generationSettings)
    assert.equal(migrated.mode, 'direct')
    assert.equal(migrated.baseUrl, '')
    assert.equal(migrated.token, '')
    assert.equal(migrated.relayToken, '')
    console.log('PASS: connection settings, enabled tags, disabled pointer/keyboard guard, saved selection recovery, failed model stays enabled, no-enabled neutral status and relay migration')
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
