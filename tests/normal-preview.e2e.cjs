// Run with an externally supplied Playwright installation, as with the other browser checks.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const assert = require('node:assert/strict')
const path = require('node:path')
;(async () => {
  const browser = await chromium.launch({ executablePath: process.env.NORMAL_TEST_BROWSER || undefined, headless: true, args: ['--enable-webgl','--use-angle=swiftshader','--enable-unsafe-swiftshader'] })
  try {
    const page = await browser.newPage({ viewport: { width: 1450, height: 980 }, acceptDownloads: true })
    await page.addInitScript(() => localStorage.setItem('g-studio-locale', 'zh-CN'))
    const errors = []; page.on('pageerror', error => errors.push(error.message))
    const base = (process.env.NORMAL_TEST_URL || 'http://127.0.0.1:5173').replace(/\/$/, '')
    await page.goto(base + '/#/scene-lighting')
    await page.getByRole('button', { name: '新建场景', exact: true }).click()
    await page.getByRole('link', { name: '精灵图切分', exact: true }).click()
    await page.locator('input[type=file]').first().setInputFiles(path.join(__dirname, '../public/scene-lighting/chest.png'))
    await page.getByRole('button', { name: '不去背', exact: true }).click()
    await page.locator('.grid-rect').waitFor()
    await page.getByRole('button', { name: '加入场景（1）', exact: true }).waitFor()
    await page.locator('.grid-rect').dblclick()
    const editor = page.getByRole('dialog', { name: '部件编辑器', exact: true })
    await editor.waitFor()
    assert.equal(await editor.getByRole('combobox', { name: '几何类型', exact: true }).inputValue(), 'silhouette')
    await editor.getByRole('textbox', { name: '部件名称', exact: true }).fill('E2E shared chest')
    await editor.getByRole('combobox', { name: '几何类型', exact: true }).selectOption('box')
    await editor.getByRole('slider', { name: '明暗细节', exact: true }).fill('2')
    await editor.getByRole('button', { name: '法线图', exact: true }).click()
    await editor.locator('.flat-preview img').waitFor()
    await editor.getByRole('button', { name: '保存并返回', exact: true }).click()
    await editor.waitFor({ state: 'hidden' })
    await page.getByRole('button', { name: '加入场景（1）', exact: true }).click()
    await page.waitForURL('**/#/scene-lighting')
    await page.locator('.object-marker').waitFor()
    assert.equal(await page.locator('.object-marker').count(), 1)
    const assetId = await page.locator('.object-marker').getAttribute('data-asset-id')
    await page.getByRole('button', { name: '编辑部件', exact: true }).click()
    await editor.getByRole('button', { name: '加入场景', exact: true }).click()
    await editor.waitFor({ state: 'hidden' })
    assert.equal(await page.locator('.object-marker').count(), 2)
    assert.deepEqual(await page.locator('.object-marker').evaluateAll(es => es.map(e => e.dataset.assetId)), [assetId, assetId])
    await page.locator('.properties-sidebar').getByRole('slider', { name: '位置 X', exact: true }).fill('5.9')
    await page.getByRole('slider', { name: '位置 Y（高度）', exact: true }).fill('4.2')
    await page.getByRole('button', { name: '编辑部件', exact: true }).click()
    await editor.getByRole('button', { name: '在精灵图中打开', exact: true }).click()
    await page.waitForURL('**/#/sprite-slicer')
    await editor.getByRole('textbox', { name: '部件名称', exact: true }).fill('E2E updated chest')
    await editor.getByRole('slider', { name: '几何高度', exact: true }).fill('2.4')
    await editor.getByRole('button', { name: '保存并返回', exact: true }).click()
    await page.getByRole('link', { name: '场景光影', exact: true }).click()
    await page.waitForURL('**/#/scene-lighting')
    assert.equal(await page.locator('.object-marker').filter({hasText:'E2E updated chest'}).count(), 2)
    assert.equal(await page.locator('.properties-sidebar').getByRole('slider', { name: '位置 X', exact: true }).inputValue(), '5.9')
    assert.equal(await page.getByRole('slider', { name: '位置 Y（高度）', exact: true }).inputValue(), '4.2')
    await page.getByRole('button', { name: '编辑部件', exact: true }).click()
    await editor.getByRole('slider', { name: '几何高度', exact: true }).fill('5')
    await editor.getByRole('button', { name: '返回场景', exact: true }).click()
    await page.getByRole('button', { name: '放弃修改', exact: true }).click()
    await page.getByRole('button', { name: '编辑部件', exact: true }).click()
    assert.equal(await editor.getByRole('slider', { name: '几何高度', exact: true }).inputValue(), '2.4')
    const downloadPromise = page.waitForEvent('download')
    await editor.getByRole('button', { name: '导出部件包 ZIP', exact: true }).click()
    const downloaded = await downloadPromise
    const zip = await require('jszip').loadAsync(require('node:fs').readFileSync(await downloaded.path()))
    assert.deepEqual(Object.keys(zip.files).sort(), ['color.png', 'normal.png', 'part.json'])
    const part = JSON.parse(await zip.file('part.json').async('string'))
    assert.equal(part.id, assetId); assert.equal(part.geometry.size[1], 2.4); assert.equal(part.normal.detailStrength, 2)
    await editor.getByRole('button', { name: '返回场景', exact: true }).click()
    await page.reload(); await page.locator('.object-marker').first().waitFor()
    assert.equal(await page.locator('.object-marker').count(), 2)
    assert.deepEqual(await page.locator('.object-marker').evaluateAll(es => es.map(e => e.dataset.assetId)), [assetId, assetId])
    if (process.env.NORMAL_TEST_SCREENSHOT) await page.screenshot({ path: process.env.NORMAL_TEST_SCREENSHOT })
    assert.deepEqual(errors, [])
    console.log('Shared part editing, references, cancellation, ZIP export and reload passed')
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exit(1) })
