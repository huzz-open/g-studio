const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const assert = require('node:assert/strict')
;(async () => {
  const browser = await chromium.launch({ executablePath: process.env.NORMAL_TEST_BROWSER || undefined, headless: true, args: ['--enable-webgl','--use-angle=swiftshader','--enable-unsafe-swiftshader'] })
  try {
    const page = await browser.newPage({ viewport: { width: 1450, height: 1000 } })
    await page.addInitScript(() => localStorage.setItem('g-studio-locale', 'zh-CN'))
    const errors=[];page.on('pageerror',e=>errors.push(e.message))
    await page.goto((process.env.NORMAL_TEST_URL || 'http://127.0.0.1:5173').replace(/\/$/,'')+'/#/scene-lighting')
    const inspect=async()=>{
      if(await page.locator('.shadow-inspector').getAttribute('open')===null)await page.locator('.shadow-inspector > summary').click()
      const button=page.getByRole('button',{name:'检查阴影落点',exact:true})
      await button.click();await page.locator('.receiver-report').waitFor()
      return page.locator('.receiver-report').innerText()
    }
    const count=(text,label)=>Number(text.match(new RegExp(label+' (\\d+)'))?.[1]??-1)
    await page.getByRole('button',{name:'物体互投影',exact:true}).click()
    const mutual=await inspect();assert.ok(count(mutual,'青花瓷瓶')>0)
    await page.getByRole('switch',{name:'接收阴影',exact:true}).uncheck()
    assert.equal(count(await inspect(),'青花瓷瓶'),0)
    await page.getByRole('switch',{name:'接收阴影',exact:true}).check()
    await page.locator('.object-marker').filter({hasText:'油纸伞'}).click()
    await page.getByRole('switch',{name:'投射阴影',exact:true}).uncheck()
    assert.equal(count(await inspect(),'青花瓷瓶'),0)
    await page.getByRole('switch',{name:'场景阴影',exact:true}).uncheck()
    const off=await inspect();for(const label of ['地面','墙面','青花瓷瓶','木箱','酒桶'])assert.equal(count(off,label),0)
    await page.getByRole('button',{name:'墙角投影',exact:true}).click()
    assert.ok(count(await inspect(),'墙面')>0)
    await page.getByRole('slider',{name:'光源高度',exact:true}).fill('2')
    const low=await page.locator('canvas').screenshot()
    await page.getByRole('slider',{name:'光源高度',exact:true}).fill('6')
    const high=await page.locator('canvas').screenshot();assert.ok(!low.equals(high))
    await page.getByRole('button',{name:'几何',exact:true}).click()
    if(process.env.SHADOW_SCREENSHOT)await page.screenshot({path:process.env.SHADOW_SCREENSHOT})
    assert.deepEqual(errors,[]);console.log('Ground, wall and cross-object shadows share the scene renderer')
  }finally{await browser.close()}
})().catch(error=>{console.error(error);process.exit(1)})
